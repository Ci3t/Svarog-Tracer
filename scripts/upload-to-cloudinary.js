#!/usr/bin/env node
/**
 * Cloudinary Batch Upload Script
 *
 * Uploads:
 * 1. Local assets from public/ → svarog-tracer/site/
 * 2. HSR game images directly from Mar-7th/StarRailRes GitHub → svarog-tracer/game/hsr/
 *
 * Usage:
 *   node scripts/upload-to-cloudinary.js
 *
 * Requirements:
 *   - CLOUDINARY_CLOUD_NAME, CLOUDINARY_API_KEY, CLOUDINARY_API_SECRET in .env
 *   - Run from project root
 */

import { v2 as cloudinary } from "cloudinary";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import dotenv from "dotenv";

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// ── Configuration ──────────────────────────────────────────────────────────

const CLOUD_NAME = process.env.CLOUDINARY_CLOUD_NAME;
const API_KEY = process.env.CLOUDINARY_API_KEY;
const API_SECRET = process.env.CLOUDINARY_API_SECRET;

const BASE_FOLDER = "svarog-tracer";
const LOCAL_ASSET_DIR = path.join(__dirname, "..", "public");
const OUTPUT_MAP = path.join(__dirname, "..", "src", "generated", "cloudinary-map.js");

const HSR_CHARACTERS = JSON.parse(fs.readFileSync(path.join(__dirname, "..", "src", "data", "characters.json"), "utf8"));

// ── Validation ─────────────────────────────────────────────────────────────

if (!CLOUD_NAME || CLOUD_NAME === "your-cloud-name") {
  console.error("❌ CLOUDINARY_CLOUD_NAME not set in .env");
  process.exit(1);
}
if (!API_KEY || API_KEY === "your-api-key") {
  console.error("❌ CLOUDINARY_API_KEY not set in .env");
  process.exit(1);
}
if (!API_SECRET || API_SECRET === "your-api-secret") {
  console.error("❌ CLOUDINARY_API_SECRET not set in .env");
  process.exit(1);
}

cloudinary.config({
  cloud_name: CLOUD_NAME,
  api_key: API_KEY,
  api_secret: API_SECRET,
});

// ── Helpers ────────────────────────────────────────────────────────────────

const assetMap = {};

function normalizeKey(filePath) {
  // Convert any path to clean relative path from public/ root
  // Handles: D:\Coding\HSR_PatternRecord\public\foo.png → foo.png
  // Handles: public/companions/Clara/foo.mp3 → companions/Clara/foo.mp3
  return filePath
    .replace(/\\/g, '/')
    .replace(/.*\bpublic\//, '');
}

function addToMap(localPath, secureUrl) {
  const key = normalizeKey(localPath);
  assetMap[key] = secureUrl;
}

async function uploadLocalFile(filePath, targetFolder) {
  const publicId = `${BASE_FOLDER}/${targetFolder}/${path.basename(filePath, path.extname(filePath))}`;

  try {
    // Check if already exists
    const existing = await cloudinary.api.resource(publicId, { resource_type: "auto" }).catch(() => null);
    if (existing) {
      console.log(`  ⏭️  Skip (exists): ${publicId}`);
      addToMap(filePath, existing.secure_url);
      return existing.secure_url;
    }
  } catch {
    // Resource doesn't exist, proceed to upload
  }

  const result = await cloudinary.uploader.upload(filePath, {
    public_id: publicId,
    overwrite: false,
    resource_type: "auto",
    eager: [
      { fetch_format: "auto", quality: "auto" },
    ],
  });

  console.log(`  ✅ Uploaded: ${publicId}`);
  addToMap(filePath, result.secure_url);
  return result.secure_url;
}

async function uploadFromUrl(remoteUrl, publicId) {
  try {
    const existing = await cloudinary.api.resource(publicId, { resource_type: "image" }).catch(() => null);
    if (existing) {
      console.log(`  ⏭️  Skip (exists): ${publicId}`);
      return existing.secure_url;
    }
  } catch {
    // Doesn't exist
  }

  const result = await cloudinary.uploader.upload(remoteUrl, {
    public_id: publicId,
    overwrite: false,
    resource_type: "image",
    eager: [
      { width: 400, crop: "limit", fetch_format: "auto", quality: "auto" },
      { width: 800, crop: "limit", fetch_format: "auto", quality: "auto" },
    ],
  });

  console.log(`  ✅ Uploaded: ${publicId}`);
  return result.secure_url;
}

function walkDir(dir, callback) {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walkDir(fullPath, callback);
    } else {
      callback(fullPath);
    }
  }
}

function writeAssetMap() {
  const entries = Object.entries(assetMap)
    .map(([k, v]) => `  "${k}": "${v}"`)
    .join(",\n");

  const content = `// Auto-generated by scripts/upload-to-cloudinary.js
// Do not edit manually. Regenerate by running: node scripts/upload-to-cloudinary.js

export const CLOUDINARY_MAP = {
${entries}
};

export const CLOUDINARY_CLOUD_NAME = "${CLOUD_NAME}";
`;

  fs.writeFileSync(OUTPUT_MAP, content, "utf8");
  console.log(`\n📝 Asset map written to: ${OUTPUT_MAP}`);
  console.log(`   Mapped ${Object.keys(assetMap).length} assets.`);
}

// ── Phase 1: Local Assets ──────────────────────────────────────────────────

async function uploadLocalAssets() {
  console.log("\n📦 Phase 1: Uploading local assets from public/...\n");

  const allowedExts = new Set([".png", ".jpg", ".jpeg", ".gif", ".webp", ".svg", ".mp3", ".ogg", ".wav"]);

  walkDir(LOCAL_ASSET_DIR, (filePath) => {
    const ext = path.extname(filePath).toLowerCase();
    if (!allowedExts.has(ext)) return;

    const relative = path.relative(LOCAL_ASSET_DIR, filePath);
    let targetFolder = path.dirname(relative).replace(/\\/g, "/");
    // Root-level files go into "root" subfolder instead of "."
    if (targetFolder === ".") targetFolder = "root";
    const fullPublicPath = path.join("public", relative);

    uploadQueue.push(() => uploadLocalFile(filePath, `site/${targetFolder}`));
    pathMap.push(fullPublicPath);
  });
}

// ── Phase 2: HSR Character Portraits from GitHub ───────────────────────────

async function uploadHsrPortraits() {
  console.log("\n🎮 Phase 2: Uploading HSR character portraits from Mar-7th/StarRailRes...\n");

  const baseUrl = "https://raw.githubusercontent.com/Mar-7th/StarRailRes/master";

  for (const char of HSR_CHARACTERS) {
    if (!char.numId) continue;

    // Portrait
    const portraitUrl = `${baseUrl}/image/character_portrait/${char.numId}.png`;
    const portraitId = `${BASE_FOLDER}/game/hsr/character_portrait/${char.numId}`;
    const portraitResult = await uploadFromUrl(portraitUrl, portraitId);
    assetMap[`game/hsr/character_portrait/${char.numId}.png`] = portraitResult;

    // Icon (optional — for completeness)
    const iconUrl = `${baseUrl}/icon/character/${char.numId}.png`;
    const iconId = `${BASE_FOLDER}/game/hsr/character_icon/${char.numId}`;
    const iconResult = await uploadFromUrl(iconUrl, iconId);
    assetMap[`game/hsr/character_icon/${char.numId}.png`] = iconResult;
  }
}

// ── Phase 3: HSR Light Cone Previews ───────────────────────────────────────

async function uploadHsrLightCones() {
  console.log("\n⚔️  Phase 3: Uploading HSR light cone previews...\n");

  // Fate collab + key light cones
  const LIGHTCONE_IDS = [
    23006, // LV.999
    23045, // Fate — A Thankless Coronation
    23046, // Fate — The Hell Where Ideals Burn
  ];

  const baseUrl = "https://raw.githubusercontent.com/Mar-7th/StarRailRes/master";

  for (const lcId of LIGHTCONE_IDS) {
    const previewUrl = `${baseUrl}/image/light_cone_preview/${lcId}.png`;
    const previewId = `${BASE_FOLDER}/game/hsr/lightcone_preview/${lcId}`;
    const result = await uploadFromUrl(previewUrl, previewId);
    assetMap[`game/hsr/lightcone_preview/${lcId}.png`] = result;
  }
}

// ── Phase 4: HSR Element Icons ─────────────────────────────────────────────

async function uploadHsrElementIcons() {
  console.log("\n✨ Phase 4: Uploading HSR element icons...\n");

  const ELEMENTS = ['Physical', 'Fire', 'Ice', 'Lightning', 'Wind', 'Quantum', 'Imaginary'];
  const baseUrl = "https://raw.githubusercontent.com/Mar-7th/StarRailRes/master";

  for (const element of ELEMENTS) {
    const iconUrl = `${baseUrl}/icon/element/${element}.png`;
    const iconId = `${BASE_FOLDER}/game/hsr/element_icon/${element}`;
    const result = await uploadFromUrl(iconUrl, iconId);
    assetMap[`game/hsr/element_icon/${element}.png`] = result;
  }
}

// ── Main ───────────────────────────────────────────────────────────────────

const uploadQueue = [];
const pathMap = [];

async function main() {
  console.log("☁️  Cloudinary Upload Script");
  console.log(`   Cloud: ${CLOUD_NAME}`);
  console.log(`   Folder: ${BASE_FOLDER}`);

  await uploadLocalAssets();

  // Execute uploads sequentially to avoid rate limits
  for (let i = 0; i < uploadQueue.length; i++) {
    try {
      await uploadQueue[i]();
    } catch (err) {
      console.error(`  ❌ Failed: ${pathMap[i]} — ${err.message}`);
    }
  }

  await uploadHsrPortraits();
  await uploadHsrLightCones();
  await uploadHsrElementIcons();

  writeAssetMap();

  console.log("\n✅ Done!");
}

main().catch((err) => {
  console.error("\n💥 Fatal error:", err);
  process.exit(1);
});

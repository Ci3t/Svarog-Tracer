function fmtRow(r) {
  const pred = r.pred ?? '—';
  const alt = r.alt ?? '—';
  const result = r.hit === 'HIT' ? '✅ HIT' : r.hit === 'ALT-HIT' ? '⚡ ALT-HIT' : '❌ MISS';
  return `| ${r.rollNum} | ${r.pos} | ${r.context} | ${pred} / ${alt} | ${r.actual} | ${result} | ${r.trendNote} | ${r.noiseNote} | ${r.switchNote || '—'} |`;
}

function fmtCheckpoint(cp) {
  return `| After roll ${cp.afterRoll} | ${cp.commons} | ${cp.noise} |`;
}

function sessionSection(s) {
  const cpRows = s.checkpoints.map(fmtCheckpoint).join('\n');
  const rbRows = s.rollByRoll.map(fmtRow).join('\n');
  const total = s.total;
  const hitRate = total ? Math.round((s.hits / total) * 100) : 0;
  const top2Rate = total ? Math.round((s.top2 / total) * 100) : 0;
  return `### Session ${s.session.id} — ${s.session.date} (${s.session.rolls.length} rolls)

**Sequence**: \`${s.session.rolls.join(' ')}\`

| Checkpoint | Commons | Noise |
|------------|---------|-------|
${cpRows}

#### Roll-by-Roll (from roll 7)

| Roll# | Pos | Context (last 6) | Pred/Alt | Actual | Result | Trend Note | Noise Note | Switch? |
|-------|-----|-----------------|----------|--------|--------|-----------|-----------|---------|
${rbRows}

#### Session Summary
- **Hit rate**: ${s.hits}/${total} = ${hitRate}%
- **Top-2 rate**: ${s.top2}/${total} = ${top2Rate}%
- **Miss patterns**: ${describeMisses(s.rollByRoll)}
- **Commons switch events**: ${describeSwitches(s.rollByRoll)}
`;
}

function describeMisses(rows) {
  const misses = rows.filter(r => r.hit === 'MISS');
  if (!misses.length) return 'None';
  const patterns = [];
  const noiseMisses = misses.filter(r => {
    const noise = r.noiseNote.includes('absent');
    return noise && !r.switchNote;
  }).length;
  const switchMisses = misses.filter(r => r.switchNote).length;
  const chaosMisses = misses.filter(r => r.pairSafety === 'danger' && r.noiseRisk > 50).length;
  if (switchMisses) patterns.push(`${switchMisses} during/after commons switches`);
  if (noiseMisses) patterns.push(`${noiseMisses} noise breaks not caught`);
  if (chaosMisses) patterns.push(`${chaosMisses} in chaos/danger board state`);
  return patterns.join('; ') || `${misses.length} general misses`;
}

function describeSwitches(rows) {
  const switches = [];
  let last = '';
  rows.forEach(r => {
    if (r.switchNote && r.switchNote !== last) {
      switches.push(`Roll ${r.rollNum}: ${r.switchNote} (full ${r.fullCommons}, recent-8 ${r.recent8Commons})`);
      last = r.switchNote;
    }
  });
  return switches.length ? switches.join('; ') : 'None detected';
}


// Generate all patch phases from 1.0 to 3.8
export function generatePatchPhases() {
  const phases = [];
  for (let major = 1; major <= 3; major++) {
    const maxMinor = major === 3 ? 8 : (major === 2 ? 7 : 6);
    for (let minor = 0; minor <= maxMinor; minor++) {
      const version = `${major}.${minor}`;
      phases.push({ version, phase: 1 });
      phases.push({ version, phase: 2 });
    }
  }
  return phases;
}

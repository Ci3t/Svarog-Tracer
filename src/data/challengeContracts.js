export const CHALLENGE_CONTRACT_ORDER = ['easy01', 'easy02', 'medium01', 'medium02', 'hard01'];

export function getChallengeContract(contractId = 'easy01') {
  return CHALLENGE_CONTRACTS[contractId] || CHALLENGE_CONTRACTS.easy01;
}

export function getNextChallengeContractId(contractId = 'easy01') {
  const currentIndex = CHALLENGE_CONTRACT_ORDER.indexOf(contractId);
  if (currentIndex < 0 || currentIndex >= CHALLENGE_CONTRACT_ORDER.length - 1) return null;
  return CHALLENGE_CONTRACT_ORDER[currentIndex + 1];
}

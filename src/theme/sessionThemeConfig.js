function mergeTheme(base, override = {}) {
  return {
    ...base,
    ...override,
    cssVars: {
      ...base.cssVars,
      ...(override.cssVars || {}),
    },
    layout: {
      ...base.layout,
      ...(override.layout || {}),
      themeOptionActiveStyles: {
        ...base.layout.themeOptionActiveStyles,
        ...(override.layout?.themeOptionActiveStyles || {}),
      },
    },
    liveStats: {
      ...base.liveStats,
      ...(override.liveStats || {}),
    },
    debugPanel: {
      ...base.debugPanel,
      ...(override.debugPanel || {}),
      stats: {
        ...base.debugPanel.stats,
        ...(override.debugPanel?.stats || {}),
      },
    },
    caverns: {
      ...base.caverns,
      ...(override.caverns || {}),
    },
    home: {
      ...base.home,
      ...(override.home || {}),
      statsTheme: {
        ...base.home.statsTheme,
        ...(override.home?.statsTheme || {}),
        online: {
          ...base.home.statsTheme.online,
          ...(override.home?.statsTheme?.online || {}),
        },
        prediction: {
          ...base.home.statsTheme.prediction,
          ...(override.home?.statsTheme?.prediction || {}),
        },
        today: {
          ...base.home.statsTheme.today,
          ...(override.home?.statsTheme?.today || {}),
        },
        total: {
          ...base.home.statsTheme.total,
          ...(override.home?.statsTheme?.total || {}),
        },
      },
    },
  };
}

const resolvedThemes = Object.fromEntries([
  ["modern", baseTheme],
  ...Object.entries(themeOverrides).map(([themeKey, override]) => [
    themeKey,
    mergeTheme(baseTheme, override),
  ]),
]);

export function getSessionThemeConfig(sessionTheme = "modern") {
  const normalizedTheme =
    sessionTheme === "winter"
      ? "arctic"
      : sessionTheme === "void"
        ? "crimson"
        : sessionTheme;
  return resolvedThemes[normalizedTheme] || resolvedThemes.modern;
}

export function getRootThemeClassName(sessionTheme = "modern") {
  return getSessionThemeConfig(sessionTheme).rootClassName;
}
